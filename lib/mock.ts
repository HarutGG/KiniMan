export function filterMock(options: {
  mediaType?: Movie["mediaType"];
  genres?: number[];
  voteGte?: number;
  year?: string;
  query?: string;
  surprise?: boolean;
}): Movie[] {
  let list = [...mockCatalog];
  if (options.mediaType) {
    list = list.filter((m) => m.mediaType === options.mediaType);
  }
  if (options.genres?.length) {
    list = list.filter((m) =>
      options.genres!.some((g) => m.genreIds.includes(g)),
    );
  }
  if (options.voteGte != null) {
    list = list.filter((m) => m.rating >= options.voteGte!);
  }
  if (options.year) {
    list = list.filter((m) => m.year === options.year);
  }
  if (options.query) {
    const q = options.query.toLowerCase();
    list = list.filter(
      (m) =>
        m.title.toLowerCase().includes(q) ||
        m.overview.toLowerCase().includes(q),
    );
  }
  if (options.surprise) {
    list = list.filter((m) => m.rating >= 7.2).sort((a, b) => a.id - b.id);
  }
  if (list.length === 0) list = mockCatalog.slice(0, 8);
  return list.slice(0, 12);
}
